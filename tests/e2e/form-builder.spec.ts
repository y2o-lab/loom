import { expect, test } from "@playwright/test";

test("builds nested form layouts, restores them and validates real input",async({page})=>{
 await page.goto("/form-builder");
 await page.getByRole("button",{name:"新しいフォーム",exact:true}).click();
 const inspector=page.locator(".loom-studio-panel--inspector");
 const save=()=>inspector.getByRole("button",{name:"設定を保存",exact:true}).click();
 await page.getByRole("button",{name:"追加: Header",exact:true}).click();
 await page.getByRole("button",{name:"選択: フォーム",exact:true}).click();
 await page.getByRole("button",{name:"追加: Panel",exact:true}).click();
 await page.getByRole("button",{name:"追加: Grid",exact:true}).click();
 await page.getByRole("button",{name:"追加: Input",exact:true}).click();
 await inspector.getByLabel("表示名",{exact:true}).fill("姓");await save();
 await page.getByRole("button",{name:"追加: Input",exact:true}).click();
 await inspector.getByLabel("表示名",{exact:true}).fill("メールアドレス");
 await inspector.getByLabel("入力形式",{exact:true}).selectOption("email");await save();
 await page.getByRole("button",{name:"選択: 参加者情報",exact:true}).click();
 await page.getByRole("button",{name:"追加: Row",exact:true}).click();
 await page.getByRole("button",{name:"追加: Select",exact:true}).click();
 await page.getByRole("button",{name:"選択: フォーム",exact:true}).click();
 await page.getByRole("button",{name:"追加: Checkbox",exact:true}).click();
 await page.getByRole("button",{name:"選択: フォーム",exact:true}).click();
 await page.getByRole("button",{name:"追加: Button",exact:true}).click();
 await page.reload();
 await expect(page.getByRole("button",{name:"選択: メールアドレス",exact:true})).toBeVisible();
 await page.getByRole("link",{name:"フォームをプレビュー",exact:true}).click();
 const submit=page.getByRole("button",{name:"申込内容を確認",exact:true});
 await submit.click();await expect(page.locator(".loom-form-error")).toBeVisible();
 await page.getByRole("textbox",{name:/^姓/}).fill("井上");
 const email=page.getByRole("textbox",{name:/^メールアドレス/});await email.fill("invalid");
 await page.getByRole("combobox",{name:/^参加コース/}).selectOption("チーム開発");
 await page.getByRole("checkbox",{name:/参加規約/}).check();
 await submit.click();await expect(page.locator(".loom-form-confirmation")).toHaveCount(0);
 expect(await email.evaluate(element=>(element as HTMLInputElement).validity.typeMismatch)).toBe(true);
 await email.fill("hanako@example.com");await submit.click();
 await expect(page.locator(".loom-form-confirmation")).toContainText("hanako@example.com");
 await expect(page.locator(".loom-form-confirmation")).toContainText("チーム開発");
 await expect(page.locator(".loom-form-confirmation")).toContainText("同意済み");
 await page.setViewportSize({width:390,height:844});
 const grid=page.locator(".loom-layout-grid");
 await expect(grid).toHaveCSS("grid-template-columns",/^[\d.]+px$/);
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 expect(overflow).toBe(false);
});
